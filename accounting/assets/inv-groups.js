// أقسام وحالات المواد الخام — مشتركة بين صفحة المخزون والجرد.
// المادة إلها عمود category (اختياري): إذا فاضي منخمّن قسمها من اسمها، فكل مادة جديدة
// (من الكتالوج، الذكاء الاصطناعي، فاتورة شراء...) بتنفرز لحالها بدون ما حدا يعمل شي.
//   olvIngCategory(ing)        → اسم القسم (المحفوظ أو المخمّن)
//   olvIngGuessCategory(name)  → القسم المخمّن من الاسم
//   olvIngStatus(ing, days)    → "urgent" | "zero" | "ok"
//   OLV_ING_CATS               → [{ name, icon }] بالترتيب اللي بينعرض فيه
(function () {
  const norm = (s) => String(s || "")
    .replace(/[ً-ْـ]/g, "")
    .replace(/[أإآ]/g, "ا").replace(/ة/g, "ه").replace(/ى/g, "ي")
    .toLowerCase().replace(/\s+/g, " ").trim();

  // الترتيب مهم: أول قاعدة بتطابق بتربح ("معسل نعناع" أراجيل مش خضار، "شراب فراولة" مشروبات مش فواكه)
  const RULES = [
    ["أراجيل", "shisha", /معسل|فحم|بربيش|ارجيل|حماله|قصدير|راس ارجيله|تبغ/],
    ["صلصات وتوابل", "flame", /صلص|كاتشب|مايونيز|مسطرد|خردل|مخلل|ملح|فلفل اسود|بهار|قرف|زعفران|كمون|توابل|ماء ورد|دبس|زعتر|سماق|(^| )خل( |$)|هيل/],
    ["مشروبات", "cup", /^ماء|^مياه|^مي |كوكا|(^| )كولا|سبرايت|بيبسي|فانتا|سفن|صودا|عصير|شراب|سيرب|ريد ?بول|طاقه|شعير|تمر هندي|موهيتو|بيره/],
    ["قهوه وشاي", "coffee", /قهوه|^بن |^بن$| بن |اسبريسو|نسكافيه|شاي|سحلب|كاكاو|كابتشينو|نسكويك/],
    ["ألبان وبيض", "snowflake", /حليب|جبن|لبنه|^لبن|كريمه|زبد|قشطه|بيض|حليب مكثف/],
    ["حلويات ومثلجات", "iceCream", /ايس ?كريم|بوظه|شوكولا|نوتيلا|كيك|دونات|بسكويت|حلو|كراميل|لوتس|مارشميلو/],
    ["لحوم ودجاج", "burger", /لحم|دجاج|ستيك|نقانق|سجق|تونه|سمك|شاورما|كباب|ببروني|مرتديلا|حبش/],
    ["مخبوزات", "cake", /خبز|صاج|كعك|توست|عجين|كرواسون|تورتيلا/],
    ["أساسيات المطبخ", "box", /سكر|زيت( |$)|طحين|ارز|^رز|مكسرات|صنوبر|زبيب|جوز|لوز|فستق|نشا|خميره|فانيلا|عسل|معكرون|باستا|شوفان/],
    ["فواكه", "star", /اناناس|برتقال|بطيخ|توت|جوافه|خوخ|رمان|عنب|فراول|كيوي|ليمون|مانج|موز|تفاح|شمام|افوكادو|كرز|اجاص|مشمش|باشن/],
    ["خضار", "salad", /بندوره|طماطم|خس|خيار|بصل|ثوم|بطاطا|فلفل|نعناع|بقدونس|جزر|ملفوف|فطر|مشروم|ذره|زيتون|كزبره|جرجير|باذنجان|كوسا|روكا/],
  ];
  const OTHER = "أخرى";
  // أسماء القواعد بالعربي الصحيح (الـ regex على نص موحّد الحروف)
  const PRETTY = { "قهوه وشاي": "قهوة وشاي" };
  window.OLV_ING_CATS = [...RULES.map(([n, icon]) => ({ name: PRETTY[n] || n, icon })), { name: OTHER, icon: "archive" }];

  window.olvIngGuessCategory = (name) => {
    const n = norm(name);
    const hit = RULES.find(([, , re]) => re.test(n));
    return hit ? (PRETTY[hit[0]] || hit[0]) : OTHER;
  };
  window.olvIngCategory = (ing) => {
    const c = String((ing && ing.category) || "").trim();
    return c || window.olvIngGuessCategory(ing && ing.name);
  };
  window.olvIngCatIcon = (cat) => (window.OLV_ING_CATS.find((c) => c.name === cat) || { icon: "tag" }).icon;

  // نفس حد "٣ أيام" بـ schema-low-stock-view.sql (view low_stock_items) حتى الصفحة والتنبيه يتفقوا
  window.OLV_URGENT_DAYS = 3;
  // بدها طلب: وصلت حد التنبيه، أو حسب البيع بتخلص خلال ٣ أيام (أو خلصت وهي عم تنباع)
  // صفر: كميتها صفر بس ما إلها حد تنبيه وما عم تنصرف — يا خلصت يا ما انعدّت أصلًا
  window.olvIngStatus = (ing, daysLeft) => {
    const stock = Number(ing.current_stock) || 0, thr = Number(ing.low_stock_threshold) || 0;
    if ((thr > 0 && stock <= thr) || (daysLeft != null && daysLeft <= window.OLV_URGENT_DAYS)) return "urgent";
    if (stock <= 0) return "zero";
    return "ok";
  };
})();
